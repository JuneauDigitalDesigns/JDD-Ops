'use client';
// Tune the agent's prompt without leaving the step.
//
// Test-calling is a loop — call, hear something wrong, fix the wording, push, call again — and
// the step used to break that loop twice: it told you to edit a file in another window, then
// gave you a terminal command to re-upload it. Both halves now live here.
//
// Save and Push stay SEPARATE buttons, for the same reason redeploy is separate from an env
// save in /manage: writing a file is cheap and reversible, changing what a live phone agent
// says to real callers is neither.
//
// Two facts about Retell drive the rest:
//   1. The prompt lives on the agent's LLM, not the agent (`general_prompt` passed to
//      update-agent is ignored for a retell-llm engine). The route resolves the bound llm_id.
//   2. Disk is the source of truth for the editor, but the route reads BACK from Retell, so an
//      edit made in the Retell dashboard is visible here instead of being silently overwritten.
//      `inSync: null` means we could not check — rendered as "couldn't check", never agreement.

import { useCallback, useEffect, useMemo, useState } from 'react';
import {
  ArrowCounterClockwise, CheckCircle, CloudArrowUp, Eye, FloppyDisk, SpinnerGap, Warning, XCircle,
} from '@phosphor-icons/react';
import type { ClientContext, SiteInfo } from '@/lib/types';

interface VersionMeta {
  id: string;
  ts: string;
  trigger: 'generated' | 'saved' | 'pushed';
  chars: number;
  delta: number;
}

const TRIGGER_LABEL: Record<VersionMeta['trigger'], string> = {
  generated: 'Generated by onboard.js',
  saved: 'Saved to disk',
  pushed: 'Pushed to Retell',
};
const TRIGGER_COLOR: Record<VersionMeta['trigger'], string> = {
  generated: 'var(--accent)',
  saved: 'var(--fg-3)',
  pushed: 'var(--accent-2)',
};

/** Minimal line LCS. Prompts are tens of lines, so the quadratic table is free. */
function lineDiff(a: string, b: string): { kind: 'ctx' | 'add' | 'del'; text: string }[] {
  const A = a.split('\n');
  const B = b.split('\n');
  const t: number[][] = Array.from({ length: A.length + 1 }, () => new Array<number>(B.length + 1).fill(0));
  for (let i = A.length - 1; i >= 0; i--) {
    for (let j = B.length - 1; j >= 0; j--) {
      t[i][j] = A[i] === B[j] ? t[i + 1][j + 1] + 1 : Math.max(t[i + 1][j], t[i][j + 1]);
    }
  }
  const out: { kind: 'ctx' | 'add' | 'del'; text: string }[] = [];
  let i = 0;
  let j = 0;
  while (i < A.length && j < B.length) {
    if (A[i] === B[j]) { out.push({ kind: 'ctx', text: A[i] }); i++; j++; }
    else if (t[i + 1][j] >= t[i][j + 1]) { out.push({ kind: 'del', text: A[i] }); i++; }
    else { out.push({ kind: 'add', text: B[j] }); j++; }
  }
  while (i < A.length) out.push({ kind: 'del', text: A[i++] });
  while (j < B.length) out.push({ kind: 'add', text: B[j++] });
  return out;
}

/** Collapse long runs of unchanged lines so the interesting part is visible. */
function trimContext(lines: ReturnType<typeof lineDiff>, keep = 2) {
  const out: (typeof lines[number] | { kind: 'gap'; text: string })[] = [];
  let run: typeof lines = [];
  const flush = () => {
    if (run.length <= keep * 2 + 1) out.push(...run);
    else {
      out.push(...run.slice(0, keep));
      out.push({ kind: 'gap', text: `… ${run.length - keep * 2} unchanged lines` });
      out.push(...run.slice(-keep));
    }
    run = [];
  };
  for (const l of lines) {
    if (l.kind === 'ctx') run.push(l);
    else { flush(); out.push(l); }
  }
  flush();
  return out;
}

export default function PromptTuner({ ctx, site }: { ctx: ClientContext; site: SiteInfo }) {
  const [prompt, setPrompt] = useState('');
  const [saved, setSaved] = useState('');
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState<'save' | 'push' | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<{ ok: boolean; text: string } | null>(null);
  const [live, setLive] = useState<{ inSync: boolean | null; error: string | null }>({ inSync: null, error: null });
  const [versions, setVersions] = useState<VersionMeta[]>([]);
  const [selected, setSelected] = useState<{ meta: VersionMeta; content: string } | null>(null);

  const qs = useMemo(
    () => new URLSearchParams({ slug: ctx.slug, site: site.slug }).toString(),
    [ctx.slug, site.slug],
  );

  const loadVersions = useCallback(async () => {
    try {
      const res = await fetch(`/api/manage/agent-prompt/versions?${qs}`, { cache: 'no-store' });
      const body = (await res.json()) as { versions?: VersionMeta[] };
      setVersions(body.versions ?? []);
    } catch {
      setVersions([]);
    }
  }, [qs]);

  useEffect(() => {
    let alive = true;
    (async () => {
      setLoading(true);
      setError(null);
      try {
        const res = await fetch(`/api/manage/agent-prompt?${qs}`, { cache: 'no-store' });
        const body = (await res.json()) as {
          prompt?: string; error?: string; inSync?: boolean | null; liveError?: string | null;
        };
        if (!alive) return;
        if (body.error) { setError(body.error); return; }
        setPrompt(body.prompt ?? '');
        setSaved(body.prompt ?? '');
        setLive({ inSync: body.inSync ?? null, error: body.liveError ?? null });
      } catch {
        if (alive) setError('Couldn’t reach the console dev server.');
      } finally {
        if (alive) setLoading(false);
      }
    })();
    void loadVersions();
    return () => { alive = false; };
  }, [qs, loadVersions]);

  const write = useCallback(async (push: boolean) => {
    setBusy(push ? 'push' : 'save');
    setResult(null);
    try {
      const res = await fetch('/api/manage/agent-prompt', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ slug: ctx.slug, site: site.slug, prompt, push }),
      });
      const body = (await res.json()) as {
        ok?: boolean; error?: string; pushed?: boolean; pushError?: string; llmId?: string; prompt?: string;
      };
      if (body.error) { setResult({ ok: false, text: body.error }); return; }
      // What was written, which differs from what was typed if the AI statement line was restored.
      const written = body.prompt ?? prompt;
      setPrompt(written);
      setSaved(written);
      if (push && body.pushed) {
        setResult({ ok: true, text: `Live — the agent is now answering with this prompt.` });
        setLive({ inSync: true, error: null });
      } else if (push) {
        setResult({ ok: false, text: body.pushError ?? 'Saved to disk, but the push did not happen.' });
      } else {
        setResult({ ok: true, text: 'Saved to disk. The live agent is unchanged until you push.' });
        setLive((l) => ({ ...l, inSync: false }));
      }
      void loadVersions();
    } catch {
      setResult({ ok: false, text: 'Request failed.' });
    } finally {
      setBusy(null);
    }
  }, [ctx.slug, site.slug, prompt, loadVersions]);

  const openVersion = useCallback(async (meta: VersionMeta) => {
    if (selected?.meta.id === meta.id) { setSelected(null); return; }
    try {
      const res = await fetch(`/api/manage/agent-prompt/versions?${qs}&id=${meta.id}`, { cache: 'no-store' });
      const body = (await res.json()) as { version?: { content: string } };
      if (body.version) setSelected({ meta, content: body.version.content });
    } catch {
      // A failed version read leaves the timeline usable.
    }
  }, [qs, selected]);

  const dirty = prompt !== saved;

  if (loading) {
    return (
      <div className="flex items-center gap-2 rounded-[14px] border border-rule bg-[var(--panel)] p-6 text-sm text-fg2">
        <SpinnerGap size={16} className="animate-spin" /> Loading the prompt…
      </div>
    );
  }
  if (error) {
    return (
      <div className="flex items-center gap-2.5 rounded-[14px] border p-5 text-sm" style={{ borderColor: 'var(--danger)', background: 'var(--danger-glow)' }}>
        <XCircle size={17} weight="fill" style={{ color: 'var(--danger)' }} />
        <span className="text-fg2">{error}</span>
      </div>
    );
  }

  return (
    <div className="grid w-full gap-4 xl:grid-cols-[minmax(0,1.5fr)_minmax(0,1fr)]">
      {/* ── editor ─────────────────────────────────────────────────────── */}
      <div className="flex flex-col overflow-hidden rounded-[14px] border border-rule bg-[var(--panel)]">
        <div className="flex flex-wrap items-center gap-2.5 border-b border-rule px-4 py-2.5">
          <span className="font-display text-[1.02rem] font-semibold">Agent prompt</span>
          {site.env.RETELL_AGENT_ID && <span className="mono text-2xs text-fg3">{site.env.RETELL_AGENT_ID}</span>}
          <span className="ml-auto">
            {live.inSync === true && !dirty ? (
              <span className="badge badge-ok"><CheckCircle size={11} weight="fill" /> In sync with Retell</span>
            ) : live.inSync === false || dirty ? (
              <span className="badge" style={{ color: 'var(--warn)', borderColor: 'rgba(200,132,42,.45)', background: 'var(--warn-glow)' }}>
                <Warning size={11} weight="fill" /> {dirty ? 'Unsaved changes' : 'Differs from the live agent'}
              </span>
            ) : (
              <span className="badge"><Eye size={11} /> Couldn’t check Retell</span>
            )}
          </span>
        </div>

        <textarea
          value={prompt}
          onChange={(e) => setPrompt(e.target.value)}
          spellCheck={false}
          className="mono min-h-[300px] w-full resize-y border-0 px-4 py-3.5 text-xs leading-[1.65] text-fg outline-none"
          style={{ background: 'var(--bg)' }}
        />

        <div className="flex flex-wrap items-center gap-2 border-t border-rule px-4 py-2.5">
          <button type="button" className="btn btn-sm" disabled={!dirty || busy !== null} onClick={() => void write(false)}>
            {busy === 'save' ? <SpinnerGap size={13} className="animate-spin" /> : <FloppyDisk size={13} />} Save to disk
          </button>
          <button type="button" className="btn btn-sm btn-primary" disabled={busy !== null} onClick={() => void write(true)}>
            {busy === 'push' ? <SpinnerGap size={13} className="animate-spin" /> : <CloudArrowUp size={13} weight="bold" />} Push to Retell
          </button>
          {result && (
            <span className="text-xs" style={{ color: result.ok ? 'var(--ok)' : 'var(--danger)' }}>{result.text}</span>
          )}
          <span className="mono ml-auto text-2xs text-fg3">{prompt.length.toLocaleString()} chars</span>
        </div>
      </div>

      {/* ── versions ───────────────────────────────────────────────────── */}
      <div className="flex flex-col overflow-hidden rounded-[14px] border border-rule bg-[var(--panel)]">
        <div className="flex items-center gap-2.5 border-b border-rule px-4 py-2.5">
          <span className="font-display text-[1.02rem] font-semibold">Versions</span>
          <span className="meta ml-auto">{versions.length} kept</span>
        </div>

        {versions.length === 0 ? (
          <p className="px-4 py-5 text-xs leading-[1.6] text-fg3">
            No versions yet. The prompt on disk is kept automatically the first time you save or
            push from here, so your first edit is already reversible.
          </p>
        ) : (
          <div className="no-scrollbar flex max-h-[290px] flex-col overflow-y-auto">
            {versions.map((v) => (
              <button
                key={v.id}
                type="button"
                onClick={() => void openVersion(v)}
                className="flex w-full items-start gap-2.5 border-b border-[var(--rule-weak)] px-4 py-2.5 text-left transition-colors hover:bg-[var(--surface)]"
                style={{ background: selected?.meta.id === v.id ? 'rgba(31,111,120,.09)' : undefined }}
              >
                <span className="mt-[5px] h-[9px] w-[9px] shrink-0 rounded-full" style={{ background: TRIGGER_COLOR[v.trigger] }} />
                <span className="min-w-0 flex-1">
                  <span className="block text-xs font-semibold text-fg">{TRIGGER_LABEL[v.trigger]}</span>
                  <span className="mono block text-2xs text-fg3">{new Date(v.ts).toLocaleString()}</span>
                </span>
                {v.delta !== 0 && (
                  <span className="mono mt-[1px] shrink-0 text-2xs font-semibold" style={{ color: v.delta > 0 ? 'var(--ok)' : 'var(--danger)' }}>
                    {v.delta > 0 ? '+' : '−'}{Math.abs(v.delta)}
                  </span>
                )}
              </button>
            ))}
          </div>
        )}

        {selected && (
          <>
            <div className="no-scrollbar max-h-[200px] overflow-y-auto border-t border-rule bg-[var(--surface)] px-4 py-3">
              <p className="meta mb-2">Diff — this version → what’s in the editor</p>
              {trimContext(lineDiff(selected.content, prompt)).map((l, i) => (
                <div
                  key={i}
                  className="mono whitespace-pre-wrap rounded-[3px] px-1.5 text-2xs leading-[1.6]"
                  style={
                    l.kind === 'add' ? { background: 'rgba(63,143,92,.14)', color: '#2c6b45' }
                    : l.kind === 'del' ? { background: 'rgba(210,84,47,.13)', color: '#9c3a1c' }
                    : { color: 'var(--fg-3)' }
                  }
                >
                  {l.kind === 'add' ? '+ ' : l.kind === 'del' ? '− ' : '  '}{l.text}
                </div>
              ))}
            </div>
            <div className="flex items-center gap-2 border-t border-rule px-4 py-2.5">
              <button
                type="button"
                className="btn btn-xs btn-accent"
                onClick={() => { setPrompt(selected.content); setSelected(null); }}
              >
                <ArrowCounterClockwise size={12} /> Restore into editor
              </button>
              <span className="meta">Loads it above — nothing reaches the live agent until you push.</span>
            </div>
          </>
        )}
      </div>
    </div>
  );
}
